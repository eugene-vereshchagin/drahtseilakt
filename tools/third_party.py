#!/usr/bin/env python3
"""Writes the code-dependency part of THIRD-PARTY.md from Cargo.lock, offline, and checks it.

Every crate compiled into a program is found by walking Cargo.lock from the program's package and following, for
each crate, only the dependencies its own manifest declares as normal ones (`[dependencies]` and every
`[target.*.dependencies]`, so all platforms at once); build-only and dev-only crates go to a second table. Licences
are read from the crates' manifests in the local cargo cache (~/.cargo/registry/src); nothing is downloaded. A crate
that is not in the cache takes its licence from tools/third-party-overrides.txt and is marked so.

Usage (python3 -I, standard library only, Python 3.11+):
  python3 -I tools/third_party.py              rewrite the part between the markers in THIRD-PARTY.md
  python3 -I tools/third_party.py --check      exit 1 if the file is out of date or a licence is missing or not
                                               compatible with GPL-3.0 (what tests/third_party.rs also checks)
  python3 -I tools/third_party.py --lock ../drahtseilakt-toolbox/Cargo.lock --root drahtseilakt-toolbox \
      --out ../drahtseilakt-toolbox/THIRD-PARTY.md   the same for another program (the toolbox)
"""

import argparse
import glob
import os
import re
import sys
import tomllib

BEGIN = "<!-- third-party:crates:begin (generated by tools/third_party.py; do not edit by hand) -->"
END = "<!-- third-party:crates:end -->"

# Licences (SPDX ids) a GPL-3.0-only program may include. An expression passes when every AND term has at least one
# OR alternative here. Kept in step with ALLOWED in crates/game/tests/third_party.rs.
ALLOWED = {
    "0BSD", "Apache-2.0", "Apache-2.0 WITH LLVM-exception", "BSD-1-Clause", "BSD-2-Clause", "BSD-3-Clause",
    "BSL-1.0", "CC0-1.0", "CDLA-Permissive-2.0", "GPL-2.0-or-later", "GPL-3.0", "GPL-3.0-only",
    "GPL-3.0-or-later", "ISC", "LGPL-2.1-or-later", "LGPL-3.0-only", "LGPL-3.0-or-later", "MIT", "MIT-0",
    "MPL-2.0", "Unicode-3.0", "Unicode-DFS-2016", "Unlicense", "Zlib",
}

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)


def tokens(expr):
    """SPDX expression tokens; the old `/` separator means OR, `A WITH B` stays one id."""
    expr = expr.replace("/", " OR ")
    out = []
    for t in re.findall(r"\(|\)|[^\s()]+", expr):
        if out and out[-1] not in ("(", ")", "AND", "OR") and t == "WITH":
            out[-1] += " WITH"
        elif out and out[-1].endswith(" WITH"):
            out[-1] += " " + t
        else:
            out.append(t)
    return out


def compatible(expr):
    """True when the SPDX expression can be met with licences in ALLOWED (OR: any side, AND: both sides)."""
    toks = tokens(expr)
    pos = 0

    def or_expr():
        nonlocal pos
        v = and_expr()
        while pos < len(toks) and toks[pos] == "OR":
            pos += 1
            v = and_expr() or v
        return v

    def and_expr():
        nonlocal pos
        v = atom()
        while pos < len(toks) and toks[pos] == "AND":
            pos += 1
            v = atom() and v
        return v

    def atom():
        nonlocal pos
        if pos >= len(toks):
            raise ValueError("unexpected end")
        t = toks[pos]
        pos += 1
        if t == "(":
            v = or_expr()
            if pos >= len(toks) or toks[pos] != ")":
                raise ValueError("missing )")
            pos += 1
            return v
        if t in (")", "AND", "OR"):
            raise ValueError(f"unexpected {t}")
        return t in ALLOWED

    try:
        v = or_expr()
        return v and pos == len(toks)
    except ValueError:
        return False


def registry_dirs():
    home = os.environ.get("CARGO_HOME") or os.path.expanduser("~/.cargo")
    return glob.glob(os.path.join(home, "registry", "src", "*"))


def cached_manifest(name, version, dirs):
    for d in dirs:
        p = os.path.join(d, f"{name}-{version}", "Cargo.toml")
        if os.path.isfile(p):
            with open(p, "rb") as f:
                return tomllib.load(f)
    return None


def normal_dep_names(manifest):
    """Package names of a manifest's normal dependencies, on every target."""
    tables = [manifest.get("dependencies", {})]
    for t in manifest.get("target", {}).values():
        tables.append(t.get("dependencies", {}))
    names = set()
    for table in tables:
        for key, spec in table.items():
            if isinstance(spec, dict) and "package" in spec:
                names.add(spec["package"])
            else:
                names.add(key)
    return {n.replace("_", "-") for n in names}


def read_overrides(path):
    out = {}
    if os.path.isfile(path):
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.split("#", 1)[0].strip()
                if line:
                    name, version, licence = line.split(None, 2)
                    out[(name, version)] = licence
    return out


def walk(lock_path, roots, skip, overrides):
    with open(lock_path, "rb") as f:
        lock = tomllib.load(f)
    by_name = {}
    for p in lock["package"]:
        by_name.setdefault(p["name"], []).append(p)

    def find(dep):
        parts = dep.split(" ")
        cands = by_name[parts[0]]
        if len(parts) > 1:
            cands = [p for p in cands if p["version"] == parts[1]]
        return cands[0]

    dirs = registry_dirs()
    root_dir = os.path.dirname(os.path.abspath(lock_path))
    info = {}

    def manifest_of(p):
        if "source" not in p:
            # a path crate: its manifest in the workspace (or a sibling repository, as the toolbox has)
            for m in glob.glob(os.path.join(root_dir, "**", "Cargo.toml"), recursive=True) + glob.glob(
                os.path.join(os.path.dirname(root_dir), "*", "crates", "*", "Cargo.toml")
            ):
                if "/target/" in m:
                    continue
                with open(m, "rb") as f:
                    t = tomllib.load(f)
                if t.get("package", {}).get("name") == p["name"]:
                    return t, "path"
            return None, "path"
        m = cached_manifest(p["name"], p["version"], dirs)
        return m, ("cache" if m else "missing")

    def walk_from(starts, follow_normal_only):
        seen = set()
        stack = list(starts)
        while stack:
            p = stack.pop()
            key = (p["name"], p["version"])
            if key in seen:
                continue
            seen.add(key)
            if key not in info:
                info[key] = (p,) + manifest_of(p)
            _, manifest, _ = info[key]
            normal = normal_dep_names(manifest) if (manifest and follow_normal_only) else None
            for d in p.get("dependencies", []):
                dp = find(d)
                if dp["name"] in skip:
                    continue
                if normal is not None and dp["name"].replace("_", "-") not in normal:
                    continue
                stack.append(dp)
        return seen

    starts = [find(r) for r in roots]
    shipped = walk_from(starts, True)
    everything = walk_from(starts, False)
    rows = []
    for key in sorted(everything, key=lambda k: (k[0].lower(), k[1])):
        p, manifest, how = info[key]
        if how == "path":
            continue
        pkg = (manifest or {}).get("package", {})
        licence = pkg.get("license")
        note = ""
        if licence is None and pkg.get("license-file"):
            licence = "license-file: " + pkg["license-file"]
        if how == "missing":
            if key in overrides:
                licence, note = overrides[key], "override"
            else:
                licence = None
        rows.append(dict(name=key[0], version=key[1], licence=licence or "", note=note, shipped=key in shipped))
    return rows


def render(rows, program):
    def table(sel):
        lines = ["| Crate | Version | Licence |", "|---|---|---|"]
        for r in sel:
            lic = r["licence"] or "**none recorded**"
            if r["note"] == "override":
                lic += " †"
            lines.append(f"| {r['name']} | {r['version']} | {lic} |")
        return lines

    shipped = [r for r in rows if r["shipped"]]
    build = [r for r in rows if not r["shipped"]]
    counts = {}
    for r in shipped:
        counts[r["licence"]] = counts.get(r["licence"], 0) + 1
    out = [
        BEGIN,
        "",
        f"Crates compiled into `{program}` on any of its platforms (Linux, Windows, macOS; an upper bound, since a "
        "crate is counted when any build in Cargo.lock enables it): {len(shipped)}, "
        "each with the licence its manifest declares (an `OR` means the crate may be used under either; we take the "
        "one compatible with GPL-3.0). Their licence texts are in each crate's source at its version on crates.io.",
        "",
        "Licences, by count: " + "; ".join(f"{v}× {k or 'none'}" for k, v in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))) + ".",
        "",
    ]
    out += table(shipped)
    out += [
        "",
        "Build-time only (build scripts and their helpers; not in the program, listed so the check sees every crate "
        f"in Cargo.lock): {len(build)}.",
        "",
    ]
    out += table(build)
    if any(r["note"] == "override" for r in rows):
        out += [
            "",
            "† Not in the local crate cache when this list was made; the licence is from "
            "`tools/third-party-overrides.txt` and is to be confirmed from the crate once it is fetched.",
        ]
    out += ["", END]
    return "\n".join(out) + "\n"


def problems(rows):
    bad = []
    for r in rows:
        if not r["licence"]:
            bad.append(f"{r['name']} {r['version']}: no licence recorded")
        elif not compatible(r["licence"]):
            bad.append(f"{r['name']} {r['version']}: licence '{r['licence']}' is not known to be GPL-3.0 compatible")
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lock", default=os.path.join(REPO, "Cargo.lock"))
    ap.add_argument("--root", action="append", help="the program's package (default: drahtseilakt)")
    ap.add_argument("--skip", action="append", default=[], help="a package never shipped (default: fuzzkit)")
    ap.add_argument("--out", default=os.path.join(REPO, "THIRD-PARTY.md"))
    ap.add_argument("--overrides", default=os.path.join(HERE, "third-party-overrides.txt"))
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    roots = a.root or ["drahtseilakt"]
    skip = set(a.skip or []) | ({"fuzzkit"} if not a.root else set())
    rows = walk(a.lock, roots, skip, read_overrides(a.overrides))
    part = render(rows, ", ".join(roots))
    try:
        with open(a.out, encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        text = "# Third-party components\n\n" + BEGIN + "\n" + END + "\n"
    if BEGIN not in text or END not in text:
        sys.exit(f"{a.out}: the markers are missing")
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + part.rstrip("\n") + tail
    bad = problems(rows)
    for b in bad:
        print("problem:", b, file=sys.stderr)
    if a.check:
        if new != text:
            print(f"{a.out} is out of date: run python3 -I tools/third_party.py", file=sys.stderr)
            sys.exit(1)
        sys.exit(1 if bad else 0)
    with open(a.out, "w", encoding="utf-8") as f:
        f.write(new)
    n = sum(r["shipped"] for r in rows)
    print(f"{a.out}: {n} crates in the program, {len(rows) - n} build-time only, {len(bad)} problems")
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
